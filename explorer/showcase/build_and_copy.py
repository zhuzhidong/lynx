# Define the Lynx example directory name
LYNX_EXAMPLE_DIR_NAME = "@lynx-example"

# External Lynx examples: a local clone of lynx-family/lynx-examples whose
# built bundles are packaged like the npm examples above. Build the clone
# first with `pnpm install && pnpm build`. Override the clone location with
# the LYNX_EXAMPLES_SOURCE environment variable.
EXTERNAL_EXAMPLES_ROOT = os.environ.get(
    "LYNX_EXAMPLES_SOURCE",
    os.path.expanduser("~/Workspace/OpenSource/lynx-examples"))
# Examples shipped through the pinned @lynx-example npm packages. The local
# clone keeps these out so the hand-written sub-menus keep matching the
# published bundle names.
NPM_PINNED_EXAMPLES = {
    "animation", "css", "fetch", "image", "layout", "lazy-bundle",
    "list", "scroll-view", "text", "view",
}


def prettify_name(name):
    parts = re.split(r"[-_]", name)
    return " ".join(part[:1].upper() + part[1:] for part in parts)


def read_example_description(example_dir, fallback):
    package_json = os.path.join(example_dir, "package.json")
    try:
        with open(package_json, encoding="utf-8") as f:
            description = json.load(f).get("description") or ""
    except (OSError, ValueError):
        description = ""
    return description.strip() or fallback


def collect_external_examples():
    """Collect every example in the local clone that produced bundles.

    Returns a list of {name, title, description, dist_dir, bundles} dicts.
    """
    examples_dir = os.path.join(EXTERNAL_EXAMPLES_ROOT, "examples")
    if not os.path.isdir(examples_dir):
        print(f"External lynx-examples clone not found at "
              f"'{EXTERNAL_EXAMPLES_ROOT}' (set LYNX_EXAMPLES_SOURCE to "
              f"enable); only the npm-pinned examples are packaged.")
        return []
    examples = []
    for name in sorted(os.listdir(examples_dir)):
        if name in NPM_PINNED_EXAMPLES:
            continue
        example_dir = os.path.join(examples_dir, name)
        dist_dir = os.path.join(example_dir, "dist")
        if not os.path.isdir(dist_dir):
            print(f"Skip external example '{name}': no dist directory "
                  f"(run pnpm build in the clone first).")
            continue
        bundles = sorted(
            filename for filename in os.listdir(dist_dir)
            if filename.endswith(".lynx.bundle"))
        if not bundles:
            print(f"Skip external example '{name}': dist has no "
                  f".lynx.bundle files.")
            continue
        examples.append({
            "name": name,
            "title": prettify_name(name),
            "description": read_example_description(
                example_dir, f"Example {prettify_name(name)}"),
            "dist_dir": dist_dir,
            "bundles": bundles,
        })
    return examples


def generate_external_menu_sources(examples):
    """Emit the menu sources for external examples.

    Multi-bundle examples get one generated sub-menu page each (built into
    menu/dist/<name>.lynx.bundle); single-bundle examples are linked
    directly from the main menu through generated-items.ts.
    """
    generated_dir = os.path.join(showcase_root_dir, "menu", "sub-menu",
                                  "lynx-examples")
    generated_items_file = os.path.join(showcase_root_dir, "menu",
                                        "generated-items.ts")
    if os.path.exists(generated_dir):
        shutil.rmtree(generated_dir)
    os.makedirs(generated_dir)

    menu_items = []
    for example in examples:
        name = example["name"]
        if len(example["bundles"]) == 1:
            url = (f"file://lynx?local://showcase/{name}/"
                   f"{example['bundles'][0]}")
        else:
            url = f"file://lynx?local://showcase/menu/{name}.lynx.bundle"
            items = ",\n".join(
                "  {\n"
                f"    title: {json.dumps(prettify_name(bundle[:-len('.lynx.bundle')]))},\n"
                f"    description: {json.dumps(example['description'])},\n"
                f"    url: {json.dumps('file://lynx?local://showcase/' + name + '/' + bundle)},\n"
                "  }"
                for bundle in example["bundles"])
            sub_menu = (
                "// GENERATED by explorer/showcase/build_and_copy.py from a\n"
                "// local lynx-family/lynx-examples clone. Do not edit.\n"
                "import { root } from '@lynx-js/react';\n"
                "import { AppContextProvider } from '@explorer/lib';\n"
                "import { ItemProps } from '@components/menu-item';\n"
                "import { Menu } from '@components/menu';\n"
                "\n"
                "const ITEMS: ItemProps[] = [\n"
                f"{items},\n"
                "];\n"
                "\n"
                "root.render(\n"
                "  <AppContextProvider>\n"
                "    <Menu items={ITEMS} />\n"
                "  </AppContextProvider>,\n"
                ");\n")
            with open(os.path.join(generated_dir, f"{name}.tsx"), "w",
                      encoding="utf-8") as f:
                f.write(sub_menu)
        menu_items.append(
            "  {\n"
            f"    title: {json.dumps(example['title'])},\n"
            f"    description: {json.dumps(example['description'])},\n"
            f"    url: {json.dumps(url)},\n"
            "  }")

    generated_items = (
        "// GENERATED by explorer/showcase/build_and_copy.py from a\n"
        "// local lynx-family/lynx-examples clone. Do not edit.\n"
        "import type { ItemProps } from '@components/menu-item';\n"
        "\n"
        "export const EXTRA_ITEMS: ItemProps[] = [\n"
        f"{',\n'.join(menu_items)},\n"
        "];\n")
    with open(generated_items_file, "w", encoding="utf-8") as f:
        f.write(generated_items)
    print(f"Generated menu sources for {len(examples)} external examples "
          f"({len(os.listdir(generated_dir))} sub-menu pages).")

